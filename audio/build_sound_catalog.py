"""Build audio/sound-catalog.json: every sound the Zipformer model can recognize, with a category icon.

Run: python3 -m audio.build_sound_catalog   (reads the model's class list from .cache/models)

The model's 527 AudioSet classes come in ontology order, so categories are index ranges, with
specific overrides where the glasses already have a dedicated icon (dog, siren, flame, bell...).
The catalog lets people pick any of these sounds in Preferences; picked sounds alert with the
category icon on the glasses.
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LABELS = ROOT / '.cache/models/sherpa-onnx-zipformer-small-audio-tagging-2024-04-15/class_labels_indices.csv'
OUT = Path(__file__).with_name('sound-catalog.json')

# (first index, last index, category, icon); first match wins, so specific ranges come first.
RANGES = [
    (74, 80, 'Animals', 'dog'), (322, 325, 'Vehicles', 'siren'), (310, 310, 'Vehicles', 'siren'),
    (298, 299, 'Weather & nature', 'smoke'), (355, 356, 'Home', 'bell'), (359, 359, 'Home', 'knock'),
    (370, 372, 'Home', 'drop'), (395, 395, 'Alarms & signals', 'clock'), (396, 397, 'Alarms & signals', 'siren'),
    (399, 400, 'Alarms & signals', 'smoke'), (406, 408, 'Machines & tools', 'clock'),
    (200, 207, 'Bells', 'bell'), (481, 483, 'Alarms & signals', 'bell'), (443, 443, 'Impacts', 'bang'),
    (444, 456, 'Water', 'drop'), (288, 297, 'Water', 'drop'),
    (0, 15, 'Voices', 'chat'), (27, 37, 'Music', 'music'), (68, 70, 'Voices', 'chat'), (16, 71, 'People', 'person'),
    (72, 136, 'Animals', 'paw'), (137, 282, 'Music', 'music'), (283, 287, 'Weather & nature', 'cloud'),
    (300, 353, 'Vehicles', 'car'), (354, 387, 'Home', 'house'), (388, 403, 'Alarms & signals', 'bell'),
    (404, 425, 'Machines & tools', 'gear'), (426, 436, 'Impacts', 'bang'), (437, 526, 'Other sounds', 'wave'),
]


def category(index):
    return next((cat, icon) for first, last, cat, icon in RANGES if first <= index <= last)


def build(path=LABELS):
    rows = list(csv.reader(path.open()))[1:]
    sounds = []
    for row in rows:
        index, label = int(row[0]), row[2]
        cat, icon = category(index)
        name = label.split(',')[0].strip()
        sounds.append(dict(label=label, name=name, category=cat, icon=icon))
    return sounds


if __name__ == '__main__':
    sounds = build()
    OUT.write_text(json.dumps(dict(
        note='Generated by audio/build_sound_catalog.py from the Zipformer AudioSet class list. '
             '"label" is the exact model class; "icon" is the glasses icon for that category.',
        sounds=sounds), indent=0) + '\n')
    counts = {}
    for s in sounds:
        counts[s['category']] = counts.get(s['category'], 0) + 1
    print(f'{len(sounds)} sounds →', ', '.join(f'{k} {v}' for k, v in sorted(counts.items())))
